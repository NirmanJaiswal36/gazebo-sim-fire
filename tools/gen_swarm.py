#!/usr/bin/env python3
"""Generate per-instance drone models for the forest swarm.

Six copies of iris_with_gimbal cannot coexist: they all bind fdm_port_in 9002
(SO_REUSEADDR only, so instances 2-6 fail bind() and their plugin aborts) and
they all advertise/subscribe the same absolute /gimbal/cmd_* topics, so one
gimbal command would drive every drone.

SDFormat cannot fix this from the world file: a <plugin> inside an <include> is
appended to the model's plugin list, it does not override a plugin already
declared inside the included model, and there is no experimental:params support
in sdformat14.  So each instance needs its own model.

This transforms the real models/iris_with_gimbal/model.sdf rather than keeping a
forked template under tools/, because a template silently drifts from whatever
it was copied from.  Every substitution asserts its hit count, so if upstream
changes the model this fails loudly instead of emitting a subtly wrong drone.

The nested <include> of model://gimbal_small_3d is deliberately left untouched,
name and all, so the ~130 lines of <control> blocks that reference
gimbal::roll_joint etc. need no edits.  Gimbal *control* is already per-instance
because those topics live in this model's own plugins.  The gimbal's two
camera-side identifiers (GstCameraPlugin udp_port, CameraZoomPlugin's derived
zoom topic) stay shared, which is inert until the camera pipeline is enabled.

Usage:  tools/gen_swarm.py [-n 6]        regenerate models/drone_*/
        tools/gen_swarm.py --check       verify on-disk output is up to date
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "models" / "iris_with_gimbal" / "model.sdf"
MODELS = REPO / "models"

FDM_PORT_BASE = 9002
FDM_PORT_STRIDE = 10

# (pattern, replacement, expected number of matches)
SUBS = [
    (r'<model name="iris_with_gimbal">', '<model name="drone_{n}">', 1),
    (r"<fdm_port_in>9002</fdm_port_in>", "<fdm_port_in>{fdm}</fdm_port_in>", 1),
    # ArduPilotPlugin advertises these (control channels 8/9/10)
    (r"<cmd_topic>/gimbal/cmd_roll</cmd_topic>",
     "<cmd_topic>/drone_{n}/gimbal/cmd_roll</cmd_topic>", 1),
    (r"<cmd_topic>/gimbal/cmd_pitch</cmd_topic>",
     "<cmd_topic>/drone_{n}/gimbal/cmd_pitch</cmd_topic>", 1),
    (r"<cmd_topic>/gimbal/cmd_yaw</cmd_topic>",
     "<cmd_topic>/drone_{n}/gimbal/cmd_yaw</cmd_topic>", 1),
    # the matching JointPositionController subscribers
    (r"<topic>/gimbal/cmd_roll</topic>",
     "<topic>/drone_{n}/gimbal/cmd_roll</topic>", 1),
    (r"<topic>/gimbal/cmd_pitch</topic>",
     "<topic>/drone_{n}/gimbal/cmd_pitch</topic>", 1),
    (r"<topic>/gimbal/cmd_yaw</topic>",
     "<topic>/drone_{n}/gimbal/cmd_yaw</topic>", 1),
]

CONFIG = """<?xml version="1.0"?>

<model>
  <name>drone_{n}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>

  <description>
    Swarm instance {n} of iris_with_gimbal.
    GENERATED by tools/gen_swarm.py -- do not edit by hand.
    fdm_port_in {fdm}, gimbal topics /drone_{n}/gimbal/cmd_*
  </description>

  <depend>
    <model>
      <uri>model://gimbal_small_3d</uri>
      <version>2.0</version>
    </model>
    <model>
      <uri>model://iris_with_standoffs</uri>
      <version>2.0</version>
    </model>
  </depend>
</model>
"""


def render(src_text, n):
    """Apply every substitution for instance n, asserting each hit count."""
    fdm = FDM_PORT_BASE + FDM_PORT_STRIDE * n
    text = src_text
    for pat, rep, expect in SUBS:
        text, hits = re.subn(pat, rep.format(n=n, fdm=fdm), text)
        if hits != expect:
            sys.exit(
                f"gen_swarm: pattern {pat!r} matched {hits}x, expected {expect}x.\n"
                f"  {SRC} has changed shape; update SUBS in {__file__}."
            )
    return text, fdm


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-n", "--count", type=int, default=6)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if on-disk output differs (no writes)")
    args = ap.parse_args()

    src_text = SRC.read_text()
    stale = []

    for n in range(args.count):
        text, fdm = render(src_text, n)
        config = CONFIG.format(n=n, fdm=fdm)
        out = MODELS / f"drone_{n}"

        if args.check:
            if (not (out / "model.sdf").exists()
                    or (out / "model.sdf").read_text() != text
                    or (out / "model.config").read_text() != config):
                stale.append(out.name)
            continue

        if out.exists():
            shutil.rmtree(out)
        out.mkdir(parents=True)
        (out / "model.sdf").write_text(text)
        (out / "model.config").write_text(config)
        print(f"  drone_{n}  fdm_port_in={fdm}  /drone_{n}/gimbal/cmd_*")

    if args.check:
        if stale:
            sys.exit(f"stale or missing: {', '.join(stale)} -- re-run gen_swarm.py")
        print(f"all {args.count} generated models up to date")
    else:
        print(f"wrote {args.count} models under {MODELS}")


if __name__ == "__main__":
    main()
